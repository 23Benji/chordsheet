// Launch screens for the iPhone/iPad home-screen app ("apple-touch-startup-image").
// iOS shows one only if its pixel size matches the screen exactly, so there is
// one per device size (iPads also in landscape). Dark only: iOS can't know the
// theme chosen inside the app, and dark is the default.
//
// Run on macOS (Chrome renders the page, like scripts/icon):
//   node scripts/splash/make-splash.mjs
// It writes public/splash/*.png and the <link> tags in src/index.html
// (between the "launch screens" markers).
//
// Then shrink them: Chrome's PNGs of the smooth gradient are ~700 KB each, but
// it has fewer than 100 colours, so a palette PNG is exact and ~4× smaller:
//   python3 -c "import glob; from PIL import Image; [Image.open(f).convert('RGB').convert('P', palette=Image.Palette.ADAPTIVE, colors=256).save(f, optimize=True) for f in glob.glob('public/splash/*.png')]"
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const CHROME = process.env.CHROME ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const root = new URL('../../', import.meta.url).pathname;
const page = new URL('splash.html', import.meta.url).pathname;

/** CSS width × height (portrait) and pixel ratio of each screen size. */
const PHONES = [
  [440, 956, 3], // 16/17 Pro Max
  [430, 932, 3], // 14 Pro Max, 15/16 Plus, 15 Pro Max
  [428, 926, 3], // 12/13 Pro Max, 14 Plus
  [420, 912, 3], // Air
  [414, 896, 3], // XS Max, 11 Pro Max
  [414, 896, 2], // XR, 11
  [402, 874, 3], // 16/17 Pro, 17
  [393, 852, 3], // 14 Pro, 15, 15 Pro, 16
  [390, 844, 3], // 12, 13, 14
  [375, 812, 3], // X, XS, 11 Pro, 12/13 mini
  [375, 667, 2], // SE, 8
];
const TABLETS = [
  [1032, 1376, 2], // iPad Pro 13" (M4)
  [1024, 1366, 2], // iPad Pro 12.9"
  [834, 1210, 2], // iPad Pro 11" (M4)
  [834, 1194, 2], // iPad Pro 11", Air 11"
  [820, 1180, 2], // iPad Air, iPad 10th
  [810, 1080, 2], // iPad 9th
  [768, 1024, 2], // iPad mini 5, older iPads
  [744, 1133, 2], // iPad mini 6/7
];

mkdirSync(`${root}public/splash`, { recursive: true });
const links = [];
const shots = [
  ...PHONES.map(([w, h, r]) => ({ w, h, r, orientation: 'portrait' })),
  ...TABLETS.flatMap(([w, h, r]) => [
    { w, h, r, orientation: 'portrait' },
    { w: h, h: w, r, orientation: 'landscape', device: [w, h] },
  ]),
];
/** Bump to make iOS (and caches) fetch new images instead of the old ones. */
const VERSION = 3;
for (const { w, h, r, orientation, device = [w, h] } of shots) {
  const file = `splash/launch-v${VERSION}-${w * r}x${h * r}.png`;
  // Chrome won't make a window narrower than ~500 px: a phone (390 px) would
  // be laid out wider and cut off on the right. So narrow screens are drawn
  // in a window k times larger with the page zoomed k× and the pixel ratio
  // divided by k — the same w × h layout, the same pixels.
  const k = w < 600 ? 2 : 1;
  execFileSync(CHROME, [
    '--headless=new',
    '--disable-gpu',
    '--hide-scrollbars',
    `--force-device-scale-factor=${r / k}`,
    `--window-size=${w * k},${h * k}`,
    `--screenshot=${root}public/${file}`,
    `file://${page}?w=${w}&h=${h}&k=${k}`,
  ], { stdio: 'ignore' });
  links.push(
    `    <link rel="apple-touch-startup-image" media="(device-width: ${device[0]}px) and (device-height: ${device[1]}px) and (-webkit-device-pixel-ratio: ${r}) and (orientation: ${orientation})" href="${file}" />`,
  );
  console.log(file);
}

const index = `${root}src/index.html`;
const html = readFileSync(index, 'utf8');
const start = '    <!-- launch screens (generated by scripts/splash/make-splash.mjs) -->';
const end = '    <!-- /launch screens -->';
const block = [start, ...links, end].join('\n');
const next = html.includes(start)
  ? html.slice(0, html.indexOf(start)) + block + html.slice(html.indexOf(end) + end.length)
  : html.replace('    <link rel="manifest"', `${block}\n    <link rel="manifest"`);
writeFileSync(index, next);
console.log(`${links.length} launch screens, links written to src/index.html`);
